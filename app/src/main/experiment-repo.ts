import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

/**
 * The test repository for DSP-1 substep 5, and the content snapshots used as
 * evidence about it.
 *
 * Two things are deliberate here. First, the repository is **generated**, not
 * hand-made: the whole point of substep 5 is that someone else can repeat the
 * experiment, and a directory that was assembled by hand cannot be repeated.
 * Second, the generated working copy lives **outside** the DSpatch repository,
 * because the agent is asked to modify it and DSpatch's own sources must not be
 * what it modifies.
 *
 * The snapshot functions exist because an agent saying it changed a file is not
 * evidence that the file changed. Hashing the bytes before and after is.
 */

export interface FileEntry {
  /** Path relative to the snapshot root, with forward slashes. */
  readonly relPath: string;
  readonly bytes: number;
  readonly sha256: string;
}

export interface TreeSnapshot {
  readonly root: string;
  readonly takenAtUtc: string;
  readonly files: readonly FileEntry[];
}

export interface ChangedFile {
  readonly relPath: string;
  readonly beforeSha256: string;
  readonly afterSha256: string;
  readonly beforeBytes: number;
  readonly afterBytes: number;
}

export interface TreeDiff {
  readonly added: readonly FileEntry[];
  readonly removed: readonly FileEntry[];
  readonly changed: readonly ChangedFile[];
  readonly unchangedCount: number;
}

/**
 * Directories left out of a snapshot.
 *
 * `.git` is the snapshot's own bookkeeping, `node_modules` is not our content,
 * and `artifacts/` is where the slow test writes its progress marker — it is
 * output, and including it would make an interrupted run look like a source
 * change.
 */
const SNAPSHOT_SKIP_DIRS = new Set(['.git', 'node_modules', 'artifacts']);

export function snapshotTree(root: string): TreeSnapshot {
  const files: FileEntry[] = [];
  const walk = (dir: string): void => {
    const entries = fs.readdirSync(dir, { withFileTypes: true });
    for (const entry of entries) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        if (!SNAPSHOT_SKIP_DIRS.has(entry.name)) {
          walk(full);
        }
        continue;
      }
      if (!entry.isFile()) {
        continue;
      }
      const bytes = fs.readFileSync(full);
      files.push({
        relPath: path.relative(root, full).split(path.sep).join('/'),
        bytes: bytes.byteLength,
        sha256: createHash('sha256').update(bytes).digest('hex'),
      });
    }
  };
  walk(root);
  files.sort((left, right) => (left.relPath < right.relPath ? -1 : 1));
  return { root, takenAtUtc: new Date().toISOString(), files };
}

export function diffSnapshots(before: TreeSnapshot, after: TreeSnapshot): TreeDiff {
  const beforeByPath = new Map(before.files.map((file) => [file.relPath, file]));
  const afterByPath = new Map(after.files.map((file) => [file.relPath, file]));
  const added: FileEntry[] = [];
  const removed: FileEntry[] = [];
  const changed: ChangedFile[] = [];
  let unchangedCount = 0;

  for (const file of after.files) {
    const previous = beforeByPath.get(file.relPath);
    if (previous === undefined) {
      added.push(file);
      continue;
    }
    if (previous.sha256 === file.sha256) {
      unchangedCount += 1;
      continue;
    }
    changed.push({
      relPath: file.relPath,
      beforeSha256: previous.sha256,
      afterSha256: file.sha256,
      beforeBytes: previous.bytes,
      afterBytes: file.bytes,
    });
  }
  for (const file of before.files) {
    if (!afterByPath.has(file.relPath)) {
      removed.push(file);
    }
  }
  return { added, removed, changed, unchangedCount };
}

/** Marker file. The generator refuses to wipe a directory that lacks it. */
