export interface GenerateResult {
  readonly targetDir: string;
  readonly files: readonly string[];
  readonly gitCommit: string | null;
  readonly gitError: string | null;
}

/** Delete failures worth explaining instead of passing along verbatim. */
const HELD_CODES = new Set(['EPERM', 'EACCES', 'EBUSY', 'ENOTEMPTY']);

/**
 * Delete a previously generated tree.
 *
 * Windows will not delete a directory that is a live process's working
 * directory, and `fs.rm` reports that as a bare `EPERM` naming only the
 * directory. That is the message that reached the UI on 14 September 2026, and
 * by itself it points at file permissions, which is the wrong place to look.
 * DSpatch runs the generated repository's test with `cwd` set here, so a test
 * runner outliving its turn blocks every later session.
 *
 * Read-only files are not the cause and are not handled here: `fs.rm` with
 * `force` already clears them, measured on Node 24.21.0.
 *
 * `maxRetries` covers a holder that is already on its way out. What retrying
 * cannot fix, this should at least name correctly.
 */
function removeGeneratedTree(target: string): void {
  try {
    fs.rmSync(target, { recursive: true, force: true, maxRetries: 10, retryDelay: 200 });
  } catch (err) {
    const code = (err as NodeJS.ErrnoException).code ?? '';
    if (!HELD_CODES.has(code)) throw err;
    throw new Error(
      `Could not delete the previous test repository at ${target} (${code}). A live ` +
        'process is holding it. Most often that is a test runner left over from an ' +
        'earlier turn, whose working directory is still inside the repository; a ' +
        'terminal or editor opened there does the same thing. Close it, or delete the ' +
        'directory by hand, and start the session again. Nothing in there is kept.',
    );
  }
}

/**
 * Create the test repository at `targetDir`.
 *
 * Refuses to run inside the DSpatch repository. The check is in code rather than
 * in a comment for the same reason the probe's workspace check is: prose does not
 * constrain anything.
 */
export function generateExperimentRepo(
  targetDir: string,
  repoRoot: string,
): GenerateResult {
  const target = path.resolve(targetDir);
  const fromRepo = path.relative(path.resolve(repoRoot), target);
  const insideRepo =
    fromRepo === '' || (!fromRepo.startsWith('..') && !path.isAbsolute(fromRepo));
  if (insideRepo) {
    throw new Error(
      `Refusing to generate the test repository at ${target}: it is inside the ` +
        `DSpatch repository ${repoRoot}. The agent modifies this repository, so it ` +
        'must be somewhere else entirely.',
    );
  }

  if (fs.existsSync(target)) {
    const entries = fs.readdirSync(target);
    if (entries.length > 0 && !fs.existsSync(path.join(target, MARKER))) {
      throw new Error(
        `Refusing to delete ${target}: it is not empty and has no ${MARKER} file, ` +
          'so it was not generated here and may be someone\'s work.',
      );
    }
    removeGeneratedTree(target);
  }

  const files = generatedFiles();
  for (const file of files) {
    const full = path.join(target, file.relPath);
    fs.mkdirSync(path.dirname(full), { recursive: true });
    // Newlines exactly as written: the content hashes are evidence, so the bytes
    // must not depend on the platform.
    fs.writeFileSync(full, file.content, 'utf8');
  }

  // Git inside the generated repository gives a readable textual diff to put
  // beside the hashes. It is this repository's git, never DSpatch's.
  let gitCommit: string | null = null;
  let gitError: string | null = null;
  try {
    const git = (...args: string[]): string =>
      execFileSync('git', args, { cwd: target, encoding: 'utf8' }).trim();
    git('init', '-q', '-b', 'main');
    git('config', 'user.name', 'DSpatch experiment');
    git('config', 'user.email', 'experiment@dspatch.invalid');
    git('config', 'core.autocrlf', 'false');
    git('add', '-A');
    git('commit', '-q', '-m', 'Generated state, before the agent touches anything');
    gitCommit = git('rev-parse', 'HEAD');
  } catch (error) {
    gitError = error instanceof Error ? error.message : String(error);
  }

  return {
    targetDir: target,
    files: files.map((file) => file.relPath),
    gitCommit,
    gitError,
  };
}
